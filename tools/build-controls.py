from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import site_header  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data' / 'agentic-controls.json'
GO = ROOT / 'go'
BASE = 'https://agentrust-io.com'

# Shared chrome. These are the only strings to change when the site's look moves.
CSS_VERSION = site_header.CSS_VERSION
OG_IMAGE_ALT = 'AgenTrust: open specifications for verifiable AI'
TAGLINE = 'Open specifications for verifiable AI'
EYEBROW = '<a href="/#chain">Across the chain</a> &middot; Mapped to OpenCRE &middot; Stable permalinks'
REPO = 'https://github.com/agentrust-io/agentrust-io.github.io/blob/main'
GENERATED_COMMENT = ('<!-- Generated by tools/build-controls.py from data/agentic-controls.json. '
                     'Edit the data and re-run it; CI fails on hand edits. -->')
GENERATED_NOTE = (f'This page is generated from <a href="{REPO}/data/agentic-controls.json">agentic-controls.json</a>\n'
                  f'  by <a href="{REPO}/tools/build-controls.py">build-controls.py</a>. Edit the data, not this file.')

ENFORCEMENT_POINTS = {'agent_startup', 'agent_shutdown', 'input', 'output', 'pre_tool_call',
                      'post_tool_call', 'post_model_call'}
SLUG = re.compile(r'^[a-z0-9]+(?:-[a-z0-9]+)*$')
CRE = re.compile(r'^\d{3}-\d{3}$')

_ONES = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten',
         'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen',
         'eighteen', 'nineteen']
_TENS = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety']


def words(n):
    if not 0 <= n < 100:
        raise ValueError(f'no word form for {n}')
    if n < 20:
        return _ONES[n]
    tens, ones = divmod(n, 10)
    return _TENS[tens] + (f'-{_ONES[ones]}' if ones else '')


def e(text):
    return escape(text, quote=True)


def load():
    data = json.loads(DATA.read_text(encoding='utf-8'))
    controls = data['controls']
    problems = []
    seen_ids, seen_slugs, families = set(), set(), []
    for c in controls:
        where = c.get('id', '<no id>')
        missing = [key for key in ('id', 'family', 'family_name', 'slug', 'name', 'enforcement_points',
                                   'requirement', 'permalink', 'opencre') if key not in c]
        if missing:
            problems.append(f'{where}: missing {", ".join(missing)}')
            continue
        if c['id'] in seen_ids:
            problems.append(f'{where}: duplicate id')
        if c['slug'] in seen_slugs or not SLUG.match(c['slug']):
            problems.append(f'{where}: slug {c["slug"]!r} is duplicated or not lowercase-hyphenated')
        seen_ids.add(c['id'])
        seen_slugs.add(c['slug'])
        if c['permalink'] != f'{BASE}/go/{c["slug"]}/':
            problems.append(f'{where}: permalink does not match slug')
        for point in c['enforcement_points']:
            if point not in ENFORCEMENT_POINTS:
                problems.append(f'{where}: unknown enforcement point {point!r}')
        if not c['opencre']:
            problems.append(f'{where}: no OpenCRE link')
        for link in c['opencre']:
            if not CRE.match(link['id']) or link['url'] != f'https://www.opencre.org/cre/{link["id"]}':
                problems.append(f'{where}: OpenCRE link {link.get("id")!r} is malformed')
        spec = c.get('spec')
        if spec is not None:
            if not spec.get('topic'):
                problems.append(f'{where}: spec needs a topic, the lowercase phrase used in prose')
            if spec.get('status') not in ('private', 'public'):
                problems.append(f'{where}: spec.status must be private or public')
            elif spec['status'] == 'public' and not (spec.get('name') and str(spec.get('url', '')).startswith('https://')):
                problems.append(f'{where}: a public spec needs a name and an https url')
        if families and families[-1] == c['family']:
            continue
        if c['family'] in families:
            problems.append(f'{where}: family {c["family"]} is not contiguous')
        families.append(c['family'])
    if problems:
        raise SystemExit('data/agentic-controls.json is invalid:\n  ' + '\n  '.join(problems))
    return data, controls


