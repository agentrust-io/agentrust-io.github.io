"""Generate /go/, the agentic control set, from data/agentic-controls.json.

The control set is cited by external standards through stable permalinks, so the
pages must never drift from the data. Edit data/agentic-controls.json, then run:

    python tools/build-controls.py          # write go/index.html and go/<slug>/index.html
    python tools/build-controls.py --check  # fail if any page differs from the data

CI runs --check. A permalink that is cited elsewhere must keep resolving, so a
control that disappears from the data is an error here, not a silent deletion.
"""
import argparse
